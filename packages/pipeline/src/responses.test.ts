import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import type { VerseEntry } from "@yada/schema";

import { ingestResponses } from "./responses.js";
import { composed1Co14, loadGolden, seedVerse, tempStaging, type TempStaging } from "./test-staging.js";

/**
 * ingest-responses is the door into the corpus. The tests that matter are the
 * refusals: each one is a way an unreviewed or incomplete entry could otherwise
 * arrive in staging looking like a good one.
 */

let staging: TempStaging;
let dir: string;

beforeEach(() => {
  staging = tempStaging();
  dir = mkdtempSync(path.join(tmpdir(), "yada-responses-"));
});

afterEach(() => {
  staging.cleanup();
  rmSync(dir, { recursive: true, force: true });
});

function writeResponse(
  entries: unknown,
  options: { model?: string; stop?: string; pericope?: string; name?: string } = {},
): void {
  const model = options.model ?? "claude-opus-5";
  const pericope = options.pericope ?? "LEV.19.1-19.37";
  writeFileSync(
    path.join(dir, options.name ?? `${pericope}.${model}.json`),
    JSON.stringify({
      pericope_id: pericope,
      model,
      stop_reason: options.stop ?? "end_turn",
      usage: { input_tokens: 1, output_tokens: 1 },
      text: JSON.stringify(entries),
    }),
  );
}

function leviticus(): VerseEntry {
  return loadGolden("lev.19.18");
}

const rows = (sql: string) => staging.db.prepare(sql).all();

describe("ingest-responses", () => {
  it("stores a valid generated verse entry as flagged", () => {
    const entry = leviticus();
    writeResponse({ verses: [entry] }, { pericope: entry.pericope_id });
    const report = ingestResponses(staging.db, dir);
    expect(report.rejected).toEqual([]);
    expect(report.stored.map((s) => s.id)).toEqual([entry.verse_id]);
    expect(rows("SELECT status FROM review_state")).toEqual([{ status: "flagged" }]);
    expect(String(rows("SELECT reason FROM review_state")[0]?.["reason"])).toMatch(/generated by claude-opus-5/);
  });

  it("stores a valid pericope entry in pericope_entries", () => {
    const entry = leviticus();
    const pericope = {
      pericope_id: entry.pericope_id,
      book: "LEV",
      schema_version: entry.schema_version,
      prompt_version: "pericope@1.0.0",
      span: { start: entry.pericope_id.split("-")[0], end: "LEV.19.37" },
      summary_one_sentence: "Holiness worked out in ordinary life.",
      key_ideas: ["holiness"],
      claims: [],
      review: { status: "flagged", flags: [] },
    };
    writeResponse({ pericope, verses: [entry] }, { pericope: entry.pericope_id });
    const report = ingestResponses(staging.db, dir);
    expect(report.rejected).toEqual([]);
    expect(rows("SELECT pericope_id FROM pericope_entries")).toEqual([{ pericope_id: entry.pericope_id }]);
  });

  it("refuses an entry claiming a human review, and stores nothing for it", () => {
    const entry = leviticus();
    entry.review.status = "human_reviewed";
    writeResponse([entry], { pericope: entry.pericope_id });
    const report = ingestResponses(staging.db, dir);
    expect(report.stored).toEqual([]);
    expect(report.rejected[0]?.reason).toMatch(/nothing generated has been reviewed/);
    expect(rows("SELECT * FROM entries")).toEqual([]);
  });

  it("refuses expert_reviewed for the same reason", () => {
    const entry = leviticus();
    entry.review.status = "expert_reviewed";
    writeResponse([entry], { pericope: entry.pericope_id });
    expect(ingestResponses(staging.db, dir).stored).toEqual([]);
  });

  it("refuses a max_tokens response outright, even when its JSON parses", () => {
    const entry = leviticus();
    writeResponse([entry], { pericope: entry.pericope_id, stop: "max_tokens" });
    const report = ingestResponses(staging.db, dir);
    expect(report.stored).toEqual([]);
    expect(report.rejected).toEqual([expect.objectContaining({ id: "*", reason: expect.stringMatching(/truncated/) })]);
  });

  it("refuses schema and contract failures rather than repairing them", () => {
    const schemaBroken = leviticus() as unknown as Record<string, unknown>;
    delete schemaBroken["close_rendering"];
    const contractBroken = leviticus();
    contractBroken.verse_id = "LEV.19.17";
    contractBroken.claims[0]!.claim = "One sentence. Two sentences.";
    writeResponse([schemaBroken, contractBroken], { pericope: leviticus().pericope_id });
    const report = ingestResponses(staging.db, dir);
    expect(report.stored).toEqual([]);
    expect(report.rejected.map((r) => r.reason).join(" ")).toMatch(/close_rendering/);
    expect(report.rejected.map((r) => r.reason).join(" ")).toMatch(/claim-atomicity/);
  });

  it("refuses a duplicate display rank and says which claims collide (Psalm 23:6, prompt 1.2)", () => {
    // Opus ranked two "Where interpretation differs" claims 1 on PSA.23.6. A
    // debated and an interpretation claim share that group, so the collision
    // is across categories; renumbering would hide it from the prompt's measurement.
    const entry = leviticus();
    const debated = entry.claims.find((c) => c.id === "LEV.19.18.c9")!;
    entry.claims.push({
      ...entry.claims[0]!,
      id: "LEV.19.18.c10",
      claim: "The neighbour is read here as a fellow Israelite.",
      category: "interpretation",
      evidence_strength: "supported",
      display_rank: debated.display_rank,
    });
    writeResponse([entry], { pericope: entry.pericope_id });
    const report = ingestResponses(staging.db, dir);
    expect(report.stored).toEqual([]);
    expect(report.rejected[0]?.reason).toMatch(
      /display-rank-unique \(\[LEV\.19\.18\.c10\] display_rank 1 is already used by claim "LEV\.19\.18\.c9" in group where_interpretation_differs\)/,
    );
  });

  it("drops the pericope object from a later part of a split pericope and keeps part 1's", () => {
    const entry = leviticus();
    const pericope = (summary: string) => ({
      pericope_id: entry.pericope_id,
      book: "LEV",
      schema_version: entry.schema_version,
      prompt_version: "pericope@1.0.0",
      span: { start: "LEV.19.11", end: "LEV.19.18" },
      summary_one_sentence: summary,
      key_ideas: ["holiness"],
      claims: [],
      review: { status: "flagged", flags: [] },
    });
    const later = { ...entry, verse_id: "LEV.19.17" };
    writeFileSync(
      path.join(dir, `${entry.pericope_id}.part1of2.claude-opus-5.json`),
      JSON.stringify({ pericope_id: entry.pericope_id, part: 1, parts: 2, verses: [entry.verse_id], model: "claude-opus-5", stop_reason: "end_turn", text: JSON.stringify({ pericope: pericope("Part one's summary."), verses: [entry] }) }),
    );
    // Asked to leave it empty; even a well-formed one from a later part is not stored.
    writeFileSync(
      path.join(dir, `${entry.pericope_id}.part2of2.claude-opus-5.json`),
      JSON.stringify({ pericope_id: entry.pericope_id, part: 2, parts: 2, verses: ["LEV.19.17"], model: "claude-opus-5", stop_reason: "end_turn", text: JSON.stringify({ pericope: pericope("Part two's summary."), verses: [later] }) }),
    );
    const report = ingestResponses(staging.db, dir);
    expect(report.rejected).toEqual([]);
    expect(report.stored.map((s) => s.id).sort()).toEqual([entry.pericope_id, "LEV.19.18", "LEV.19.17"].sort());
    expect(String(rows("SELECT payload FROM pericope_entries")[0]?.["payload"])).toMatch(/Part one's summary/);
  });

  it("refuses a verse a part was not asked for, so it cannot collide with the part that was", () => {
    const entry = leviticus();
    writeResponse([entry], { pericope: entry.pericope_id, name: `${entry.pericope_id}.part2of2.claude-opus-5.json` });
    const file = path.join(dir, `${entry.pericope_id}.part2of2.claude-opus-5.json`);
    const body = JSON.parse(readFileSync(file, "utf8"));
    writeFileSync(file, JSON.stringify({ ...body, part: 2, parts: 2, verses: ["LEV.19.17"] }));
    const report = ingestResponses(staging.db, dir);
    expect(report.stored).toEqual([]);
    expect(report.rejected[0]?.reason).toMatch(/part 2 of 2 was asked for LEV\.19\.17, not LEV\.19\.18/);
  });

  it("refuses an entry for a different pericope than the one requested", () => {
    writeResponse([leviticus()], { pericope: "LEV.18.1-18.30" });
    expect(ingestResponses(staging.db, dir).rejected[0]?.reason).toMatch(/request was for LEV\.18\.1-18\.30/);
  });

  it("refuses the same verse from two models unless --model chooses", () => {
    const entry = leviticus();
    writeResponse([entry], { pericope: entry.pericope_id, model: "claude-opus-5" });
    writeResponse([entry], { pericope: entry.pericope_id, model: "claude-sonnet-5" });

    const ambiguous = ingestResponses(staging.db, dir);
    expect(ambiguous.stored).toEqual([]);
    expect(ambiguous.rejected[0]?.reason).toMatch(/2 models.*--model/);

    const chosen = ingestResponses(staging.db, dir, { model: "claude-sonnet-5" });
    expect(chosen.stored).toEqual([expect.objectContaining({ id: entry.verse_id, model: "claude-sonnet-5" })]);
    expect(chosen.skipped).toBe(1);
  });

  it("never promotes: new content over a reviewed entry goes back to flagged, and old verdicts are dropped", () => {
    const entry = leviticus();
    staging.db.prepare("INSERT INTO review_state (verse_id, status, rating, reason, updated_at) VALUES (?, 'human_reviewed', 5, 'ok', 'then')").run(entry.verse_id);
    staging.db.prepare(
      "INSERT INTO adversary_flags VALUES (?, ?, 'unsupported', 'critical', 'about the old text', 'claude-sonnet-5', 'then')",
    ).run(entry.verse_id, entry.claims[0]!.id);

    writeResponse([entry], { pericope: entry.pericope_id });
    ingestResponses(staging.db, dir);
    expect(rows("SELECT status FROM review_state")).toEqual([{ status: "flagged" }]);
    expect(rows("SELECT * FROM adversary_flags")).toEqual([]);
  });

  it("keeps paid adversary verdicts when the same text is ingested again", () => {
    const entry = leviticus();
    writeResponse([entry], { pericope: entry.pericope_id });
    ingestResponses(staging.db, dir);
    staging.db.prepare(
      "INSERT INTO adversary_flags VALUES (?, ?, 'unsupported', 'minor', 'still about this text', 'claude-sonnet-5', 'then')",
    ).run(entry.verse_id, entry.claims[0]!.id);

    ingestResponses(staging.db, dir);
    expect(rows("SELECT note FROM adversary_flags")).toEqual([{ note: "still about this text" }]);
  });

  it("assembles composed output with the gloss derived from the database it stores into", () => {
    // ingest used to derive from the shared content/staging.db whatever
    // database it was handed, so a temp staging.db got someone else's words.
    seedVerse(staging.db, "1CO.14.34", [{ surface: "σιγάτωσαν", lemma: "σιγάω", strongs: "G4601" }]);
    writeResponse(composed1Co14(), { pericope: "1CO.14.26-14.40" });
    const report = ingestResponses(staging.db, dir);
    expect(report.rejected).toEqual([]);
    expect(report.stored.map((s) => `${s.kind} ${s.id}`)).toEqual(["pericope 1CO.14.26-14.40", "verse 1CO.14.34"]);
    const stored = JSON.parse(String(rows("SELECT payload FROM entries")[0]?.["payload"])) as VerseEntry;
    expect(stored.gloss.map((word) => word.surface)).toEqual(["σιγάτωσαν"]);
    expect(stored.review.status).toBe("flagged");
  });

  it("rejects a composed response whose pericope id does not parse, and ingests the rest", () => {
    writeResponse(composed1Co14(), { pericope: "1CO.99.1-99.2" });
    const entry = leviticus();
    writeResponse([entry], { pericope: entry.pericope_id });
    const report = ingestResponses(staging.db, dir);
    expect(report.rejected).toEqual([expect.objectContaining({ id: "*", reason: expect.stringMatching(/not a pericope id/) })]);
    expect(report.stored.map((s) => s.id)).toEqual([entry.verse_id]);
  });

  it("records an unreadable response instead of throwing", () => {
    writeFileSync(path.join(dir, "X.1.1-1.2.claude-opus-5.json"), JSON.stringify({ text: "I can't help with that." }));
    writeFileSync(path.join(dir, "broken.json"), "{not json");
    const report = ingestResponses(staging.db, dir);
    expect(report.rejected).toHaveLength(2);
  });
});
