import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";

import { VerseEntrySchema, type VerseEntry } from "@yada/schema";

import { DDL } from "./db.js";
import { scriptFor } from "./derive.js";
import { GOLDEN } from "./paths.js";
import { storeVerseEntry } from "./store.js";

let dir: string;
let db: DatabaseSync;

const fixture = (): VerseEntry =>
  VerseEntrySchema.parse(JSON.parse(readFileSync(path.join(GOLDEN, "lev.19.18.json"), "utf8")));

const state = (): { status: string; rating: number | null; reason: string | null; decision?: string | null } =>
  db.prepare("SELECT * FROM review_state WHERE verse_id = 'LEV.19.18'").get() as never;

beforeEach(() => {
  dir = mkdtempSync(path.join(tmpdir(), "yada-store-"));
  db = new DatabaseSync(path.join(dir, "staging.db"));
  db.exec(DDL);
  // The review tool adds this column; storing must not destroy it.
  db.exec("ALTER TABLE review_state ADD COLUMN decision TEXT");
});

afterEach(() => {
  db.close();
  rmSync(dir, { recursive: true, force: true });
});

/** What the review tool does when John approves. */
function approve(): void {
  db.prepare(
    "UPDATE review_state SET status = 'human_reviewed', rating = 5, decision = 'approved' WHERE verse_id = 'LEV.19.18'",
  ).run();
}

describe("storing an entry over an existing review", () => {
  it("leaves a human approval intact when the same content is stored again", () => {
    // The bug: re-importing the fixture as `flagged` compared statuses, saw a
    // difference, and replaced the approval.
    storeVerseEntry(db, fixture(), "flagged", "imported from golden/");
    approve();
    storeVerseEntry(db, fixture(), "flagged", "imported from golden/");
    expect(state()).toMatchObject({ status: "human_reviewed", rating: 5, decision: "approved" });
  });

  it("sends changed content back to review, and says why", () => {
    storeVerseEntry(db, fixture(), "flagged", "imported from golden/");
    approve();
    const changed = { ...fixture(), whats_happening: `${fixture().whats_happening} Revised.` };
    storeVerseEntry(db, changed, "flagged", "generated by claude-opus-5");
    const after = state();
    expect(after.status).toBe("flagged");
    expect(after.rating).toBeNull();
    expect(after.decision).toBeNull();
    expect(after.reason).toMatch(/content changed since last review/);
  });

  it("creates review state for a new entry", () => {
    storeVerseEntry(db, fixture(), "flagged", "imported from golden/");
    expect(state()).toMatchObject({ status: "flagged", reason: "imported from golden/" });
  });
});

describe("script by book", () => {
  it("treats every Old Testament book as Hebrew, not only the four from the genre gate", () => {
    for (const book of ["GEN", "EXO", "JOB", "MAL", "PSA"]) expect(scriptFor(book), book).toBe("hebrew");
    for (const book of ["MAT", "JHN", "REV"]) expect(scriptFor(book), book).toBe("greek");
  });
});
