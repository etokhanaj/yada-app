#!/usr/bin/env node
/**
 * The BSB's own paragraph starts (RU-6), read out of the Berean tables into src/data/paragraphs.generated.ts.
 *
 * RU-6 (fresh-eyes review, approved by John 23 Oct 2026): the reader sets the text in the BSB's paragraphs, not a
 * line per verse. The tables carry them in the "Par" column as `<p class=|…|>` on the word that opens one. VerseId
 * is set only on a verse's first word, so it is carried forward. A verse starts a paragraph when any of its words
 * opens one: a break inside a verse moves to the verse's start, since the reader selects whole verses.
 * `<span class=|red|>` in the same column is red letter, not a paragraph, and `<br />` is a line break.
 *
 * Output: per book, the paragraph-start verses as chapter*1000+verse, delta-encoded in base 36 and comma-joined.
 *
 * Run alone; the tables are gitignored, so a worktree points YADA_BSB_TABLES at the main checkout's copy.
 */

import { createReadStream, writeFileSync } from "node:fs";
import path from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const source = process.env.YADA_BSB_TABLES ?? path.join(appRoot, "../..", "content", "raw", "bsb-tables", "bsb_tables.tsv");
const target = path.join(appRoot, "src", "data", "paragraphs.generated.ts");

// The tables' book names in canonical order; index + 1 is the book's number in a verse ord (@yada/schema verseOrd).
// "Psalm" and "Song of Solomon" are the BSB's spellings of PSA and SNG.
const NAMES = [
  "Genesis", "Exodus", "Leviticus", "Numbers", "Deuteronomy", "Joshua", "Judges", "Ruth", "1 Samuel", "2 Samuel",
  "1 Kings", "2 Kings", "1 Chronicles", "2 Chronicles", "Ezra", "Nehemiah", "Esther", "Job", "Psalm", "Proverbs",
  "Ecclesiastes", "Song of Solomon", "Isaiah", "Jeremiah", "Lamentations", "Ezekiel", "Daniel", "Hosea", "Joel",
  "Amos", "Obadiah", "Jonah", "Micah", "Nahum", "Habakkuk", "Zephaniah", "Haggai", "Zechariah", "Malachi",
  "Matthew", "Mark", "Luke", "John", "Acts", "Romans", "1 Corinthians", "2 Corinthians", "Galatians", "Ephesians",
  "Philippians", "Colossians", "1 Thessalonians", "2 Thessalonians", "1 Timothy", "2 Timothy", "Titus", "Philemon",
  "Hebrews", "James", "1 Peter", "2 Peter", "1 John", "2 John", "3 John", "Jude", "Revelation",
];

/** Book number → set of chapter*1000+verse that start a paragraph. */
const starts = new Map(NAMES.map((_, i) => [i + 1, new Set()]));
let columns = null;
let verse = null;

for await (const line of createInterface({ input: createReadStream(source, "utf8"), crlfDelay: Infinity })) {
  const cells = line.split("\t");
  if (columns === null) {
    if (cells.includes("VerseId")) columns = { id: cells.indexOf("VerseId"), par: cells.indexOf("Par") };
    continue;
  }
  const id = cells[columns.id]?.trim() ?? "";
  if (id !== "") {
    const m = /^(.+) (\d+):(\d+)$/.exec(id);
    const book = m === null ? -1 : NAMES.indexOf(m[1]) + 1;
    if (m === null || book === 0) {
      // Refused, not skipped: a book lost here would read as one paragraph a chapter without a word why.
      console.error(`paragraphs: unreadable VerseId "${id}"`);
      process.exit(1);
    }
    verse = { book, local: Number(m[2]) * 1000 + Number(m[3]) };
  }
  if (verse !== null && (cells[columns.par] ?? "").includes("<p class=|")) starts.get(verse.book).add(verse.local);
}

if (columns === null) {
  console.error(`paragraphs: no VerseId header in ${source}`);
  process.exit(1);
}
for (const [book, set] of starts) {
  if (set.size === 0) {
    console.error(`paragraphs: ${NAMES[book - 1]} has no paragraph starts`);
    process.exit(1);
  }
}

const encoded = [...starts.values()].map((set) => {
  let last = 0;
  return [...set]
    .sort((a, b) => a - b)
    .map((n) => {
      const d = n - last;
      last = n;
      return d.toString(36);
    })
    .join(",");
});

writeFileSync(
  target,
  `// Generated by scripts/sync-paragraphs.mjs from the BSB tables. Do not edit.
// Per book in canonical order: paragraph-start verses as chapter*1000+verse, delta-encoded, base 36.
export const PARAGRAPH_STARTS: readonly string[] = ${JSON.stringify(encoded, null, 0).replace(/","/g, '",\n  "').replace(/^\["/, '[\n  "').replace(/"\]$/, '",\n]')};
`,
);
const total = [...starts.values()].reduce((n, s) => n + s.size, 0);
console.log(`paragraphs: ${total} starts in ${starts.size} books → ${path.relative(appRoot, target)}`);
