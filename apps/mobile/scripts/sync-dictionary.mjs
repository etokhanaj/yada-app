#!/usr/bin/env node
/**
 * The dictionary and the guide titles Search finds (DI-03, DI-04, PD-04, IA-06), read out of every book's
 * Understand bundle into src/data/dictionary.generated.ts.
 *
 * Only John's Understand file ships in the app; the other 65 download when their book opens (DN-05). Search has
 * to find "church" or "The Word became flesh" before any of those files is on the phone, so the terms and the
 * passage titles are lifted out here, as the bundles hold them: no word is written, merged or reworded. A term
 * whose definition differs between books keeps the one most books carry (ties: the earliest book).
 *
 * Run by sync-bundles.mjs, or alone after `yada understand` and `yada manifest`.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
// A worktree has no content/bundles (gitignored): YADA_BUNDLES points at the main checkout's, and YADA_MANIFEST at
// a manifest matching the app's bundled.generated.ts when content/bundles has moved on past it.
const source = process.env.YADA_BUNDLES ?? path.join(appRoot, "../..", "content", "bundles");
const target = path.join(appRoot, "src", "data", "dictionary.generated.ts");

const manifest = JSON.parse(readFileSync(process.env.YADA_MANIFEST ?? path.join(source, "manifest.json"), "utf8"));
const understand = manifest.understand ?? [];
const KINDS = new Set(["kt", "names", "other"]);

/** term -> { kinds: Map<kind, books>, defs: Map<definition, books>, uses: [ord, count][] } */
const terms = new Map();
const guides = [];

for (const bundle of understand) {
  const file = path.join(source, bundle.file);
  if (!existsSync(file)) {
    // Refused, not skipped: a dictionary missing a book would answer "no results" for its words without a word why.
    console.error(`dictionary: ${bundle.file} is in the manifest but not in content/bundles`);
    process.exit(1);
  }
  const db = new DatabaseSync(file, { readOnly: true });
  const keyWords = "FROM verses v, json_each(json_extract(v.layers, '$.deeper.key_words')) k";
  const term = "json_extract(k.value, '$.term')";
  // Each kind and definition a book gives a term counts once for that book. Counting per (kind, definition)
  // group counted a book twice for a term it carried two ways, and summed its verses across the groups.
  const forms = db
    .prepare(
      `SELECT ${term} AS term, json_extract(k.value, '$.kind') AS kind, json_extract(k.value, '$.definition') AS definition
         ${keyWords}
        GROUP BY term, kind, definition
        ORDER BY min(v.ord)`,
    )
    .all();
  const inBook = new Map();
  for (const r of forms) {
    if (!KINDS.has(r.kind)) {
      console.error(`dictionary: ${bundle.file} has "${r.term}" of kind "${r.kind}"; expected kt, names or other`);
      process.exit(1);
    }
    const seen = inBook.get(r.term) ?? { kinds: new Set(), defs: new Set() };
    seen.kinds.add(r.kind);
    seen.defs.add(r.definition);
    inBook.set(r.term, seen);
  }
  for (const [t, seen] of inBook) {
    const entry = terms.get(t) ?? { kinds: new Map(), defs: new Map(), uses: [] };
    for (const kind of seen.kinds) entry.kinds.set(kind, (entry.kinds.get(kind) ?? 0) + 1);
    for (const def of seen.defs) entry.defs.set(def, (entry.defs.get(def) ?? 0) + 1);
    terms.set(t, entry);
  }
  // The verses naming a term, by term alone, so a verse is counted once whatever kind or definition it carries.
  for (const u of db.prepare(`SELECT ${term} AS term, min(v.ord) AS first, count(DISTINCT v.ord) AS verses ${keyWords} GROUP BY term`).all()) {
    terms.get(u.term).uses.push([u.first, u.verses]);
  }
  for (const p of db.prepare("SELECT passage_id, label FROM passages ORDER BY start_ord, end_ord").all()) guides.push([p.label, p.passage_id]);
  db.close();
}

/** The value most books carry; Map keeps insertion order, which is book order, so ties go to the earliest. */
const commonest = (counts) => [...counts.entries()].reduce((best, next) => (next[1] > best[1] ? next : best))[0];

const dictionary = [...terms.entries()]
  .sort(([a], [b]) => a.localeCompare(b, "en", { sensitivity: "base" }))
  .map(([term, e]) => [term, commonest(e.kinds), commonest(e.defs), e.uses.sort((a, b) => a[0] - b[0]).flat()]);

writeFileSync(
  target,
  `// Generated by scripts/sync-dictionary.mjs from the Understand bundles in content/bundles/manifest.json. Do not edit.\n\n` +
    `/** kt: key terms; names: people and places; other: everything else (unfoldingWord Translation Words' own folders). */\n` +
    `export type DictionaryKind = "kt" | "names" | "other";\n\n` +
    `/** [term, kind, definition, uses]: uses are pairs, the first verse's ord in a book and how many verses there name it. */\n` +
    `export type DictionaryRow = readonly [string, DictionaryKind, string, readonly number[]];\n\n` +
    `/** The bundles this was read from, so a test can tell when it is older than the manifest. */\n` +
    `export const DICTIONARY_FROM: readonly string[] = ${JSON.stringify(understand.map((u) => u.file))};\n\n` +
    `export const DICTIONARY: readonly DictionaryRow[] = [\n${dictionary.map((row) => `  ${JSON.stringify(row)},`).join("\n")}\n];\n\n` +
    `/** [title, passage id]: every guide's passage title, in Bible order. */\n` +
    `export const GUIDES: readonly (readonly [string, string])[] = [\n${guides.map((g) => `  ${JSON.stringify(g)},`).join("\n")}\n];\n`,
);
console.log(`dictionary: ${dictionary.length} terms, ${guides.length} guide titles from ${understand.length} books -> src/data/dictionary.generated.ts`);
